// The SDK sends people to /login?from_url=<full url>, but the login page reads ?returnTo=<path>.
// Translate once (same-origin paths only) so a login from /crm lands back on /crm.
function LoginRoute() {
  const q = new URLSearchParams(window.location.search);
  const from = q.get('from_url');
  if (from && !q.get('returnTo')) {
    try {
      const u = new URL(from, window.location.origin);
      if (u.origin === window.location.origin) {
        q.delete('from_url'); q.set('returnTo', u.pathname + u.search);
        window.history.replaceState(null, '', '/login?' + q.toString());
      }
    } catch { /* ignore */ }
  }
  return <Login />;
}
